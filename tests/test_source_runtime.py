import shutil

import pytest

import asterion.artifacts.source as source
from asterion.contracts.errors import ContractError, IntegrityError


def checkout(path):
    path.mkdir(parents=True)
    (path / "pyproject.toml").write_text('[project]\nname = "asterion-md"\n')
    target = path / "src/asterion/artifacts/source.py"
    target.parent.mkdir(parents=True)
    target.write_text("SOURCE = 1\n")
    return path


def test_installed_root_prefers_calling_checkout(tmp_path, monkeypatch):
    repository = checkout(tmp_path / "repository")
    nested = repository / "work"
    nested.mkdir()
    monkeypatch.chdir(nested)
    monkeypatch.setattr(
        source, "__file__", str(tmp_path / "venv/site-packages/asterion/artifacts/source.py")
    )
    assert source.project_root() == repository


def test_editable_root_falls_back_to_source_location(tmp_path, monkeypatch):
    repository = checkout(tmp_path / "repository")
    unrelated = tmp_path / "unrelated"
    unrelated.mkdir()
    monkeypatch.chdir(unrelated)
    monkeypatch.setattr(source, "__file__", str(repository / "src/asterion/artifacts/source.py"))
    assert source.project_root() == repository


def test_unrelated_project_is_not_used_for_lineage(tmp_path, monkeypatch):
    (tmp_path / "pyproject.toml").write_text('[project]\nname = "another-project"\n')
    monkeypatch.chdir(tmp_path)
    monkeypatch.setattr(
        source, "__file__", str(tmp_path / "venv/site-packages/asterion/artifacts/source.py")
    )
    with pytest.raises(ContractError, match="source checkout"):
        source.project_root()


def test_invalid_toml_marker_is_ignored(tmp_path, monkeypatch):
    repository = checkout(tmp_path / "repository")
    nested = repository / "nested"
    nested.mkdir()
    (nested / "pyproject.toml").write_text("[[malformed")
    monkeypatch.chdir(nested)
    assert source.project_root() == repository


def test_matching_installed_package_is_attested(tmp_path, monkeypatch):
    repository = checkout(tmp_path / "repository")
    package = tmp_path / "installed/asterion"
    shutil.copytree(repository / "src/asterion", package)
    bytecode = package / "artifacts/__pycache__/source.pyc"
    bytecode.parent.mkdir()
    bytecode.write_bytes(b"irrelevant generated bytecode")
    monkeypatch.setattr(source, "__file__", str(package / "artifacts/source.py"))
    source.assert_runtime_source(repository)


def test_stale_installed_source_is_rejected(tmp_path, monkeypatch):
    repository = checkout(tmp_path / "repository")
    package = tmp_path / "installed/asterion"
    shutil.copytree(repository / "src/asterion", package)
    (package / "artifacts/source.py").write_text("SOURCE = 2\n")
    monkeypatch.setattr(source, "__file__", str(package / "artifacts/source.py"))
    with pytest.raises(IntegrityError, match="differs"):
        source.assert_runtime_source(repository)


def test_missing_installed_input_is_rejected(tmp_path, monkeypatch):
    repository = checkout(tmp_path / "repository")
    (repository / "src/asterion/viewer.html").write_text("actual viewer")
    package = tmp_path / "installed/asterion"
    shutil.copytree(repository / "src/asterion", package)
    (package / "viewer.html").unlink()
    monkeypatch.setattr(source, "__file__", str(package / "artifacts/source.py"))
    with pytest.raises(IntegrityError, match="differs"):
        source.assert_runtime_source(repository)
